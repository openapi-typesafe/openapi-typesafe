import { describe, expect, it } from "vitest";
import { decodeDependentResults } from "../../src/application/dependents-codecs.ts";
import { DEPENDENTS_RESULTS_PATH } from "../../src/application/layout.ts";
import type { CommandRun } from "../../src/application/ports.ts";
import { checkDependents } from "../../src/application/use-cases/check-dependents.ts";
import { type DependentProject, PackageManager } from "../../src/domain/dependent-project.ts";
import {
  DependentStatus,
  GeneratedFileStatus,
  StepStatus,
} from "../../src/domain/dependent-result.ts";
import type { SwitchedPackageSpecs } from "../../src/domain/package-switch.ts";
import { type FakeCommandEffect, FakeCommandRunner } from "../fakes/fake-command-runner.ts";
import { FakeProjectSwitcher } from "../fakes/fake-project-switcher.ts";
import { InMemoryFileStore } from "../fakes/in-memory-file-store.ts";
import { RecordingDirectoryEraser } from "../fakes/recording-directory-eraser.ts";
import { RecordingLogger } from "../fakes/recording-logger.ts";

const COMMIT = "a".repeat(40);
const SPECS: SwitchedPackageSpecs = {
  "openapi-typesafe": "file:/t/a.tgz",
  "openapi-typesafe-fetch": "file:/t/b.tgz",
  "openapi-typesafe-react-query": "file:/t/c.tgz",
  "openapi-typesafe-helpers": "file:/t/d.tgz",
};

const PROJECT: DependentProject = {
  id: "demo",
  repository: "https://github.com/owner/demo",
  commit: COMMIT,
  packageManager: PackageManager.Pnpm,
  directory: "app",
  steps: [
    { name: "generate", command: ["pnpm", "run", "gen"] },
    { name: "typecheck", command: ["pnpm", "run", "typecheck"] },
    { name: "test", command: ["pnpm", "test"] },
  ],
  generatedFiles: ["gen/schema.ts", "gen/never.ts"],
  notes: "",
};

const isCandidate = (run: CommandRun): boolean => run.cwd.includes("/candidate");
const commandOf = (run: CommandRun): string => run.command.join(" ");

/** A project whose commit must be fetched and whose generate step writes a schema. */
function defaultEffect(run: CommandRun): FakeCommandEffect {
  if (commandOf(run).startsWith("git cat-file")) {
    return { exitCode: 1 };
  }
  if (commandOf(run) === "pnpm run gen") {
    const product = isCandidate(run) ? "openapi-typesafe" : "openapi-typescript";
    return { writes: { "gen/schema.ts": `// This file was auto-generated by ${product}.\n` } };
  }
  return {};
}

function setUp(script: (run: CommandRun) => FakeCommandEffect = defaultEffect) {
  const work = new InMemoryFileStore();
  const cache = new InMemoryFileStore();
  const dependencies = {
    runner: new FakeCommandRunner(work, script),
    switcher: new FakeProjectSwitcher(),
    eraser: new RecordingDirectoryEraser(work),
    work,
    cache,
    logger: new RecordingLogger(),
    intentionalDifferences: [],
  };
  const input = { projects: [PROJECT], specs: SPECS, timeoutMs: 1_000, stepLogDirectory: "/logs" };
  return { dependencies, input, run: () => checkDependents(dependencies, input) };
}

/** A script that fails one command in the candidate run and behaves like the default otherwise. */
const failingInCandidate =
  (command: string, effect: FakeCommandEffect) =>
  (run: CommandRun): FakeCommandEffect =>
    isCandidate(run) && commandOf(run) === command ? effect : defaultEffect(run);

describe("checkDependents", () => {
  it("checkDependents runs both variants in order and passes a project that works after the switch", async () => {
    const { dependencies, run } = setUp();

    const [result] = await run();

    expect(result).toMatchObject({ projectId: "demo", status: DependentStatus.Passed });
    expect(result?.baseline.map((step) => step.name)).toEqual([
      "fetch",
      "checkout",
      "install",
      "generate",
      "typecheck",
      "test",
    ]);
    expect(result?.candidate.every((step) => step.status === StepStatus.Passed)).toBe(true);
    expect(dependencies.runner.commandLines).toContain(
      `git fetch --quiet --depth 1 https://github.com/owner/demo ${COMMIT}`,
    );
    expect(dependencies.runner.commandLines).toContain(
      "pnpm install --ignore-scripts --no-frozen-lockfile",
    );
  });

  it("checkDependents runs the install and steps in the project directory with per-step logs", async () => {
    const { dependencies, run } = setUp();

    await run();

    const install = dependencies.runner.runs.find((r) => commandOf(r).startsWith("pnpm install"));
    expect(install?.cwd).toBe("/memory/checkouts/demo/baseline/app");
    expect(install?.timeoutMs).toBe(1_000);
    expect(install?.logPath).toBe("/logs/demo/baseline/install.log");
  });

  it("checkDependents pins the baseline to upstream and switches the candidate", async () => {
    const { dependencies, run } = setUp();

    await run();

    expect(dependencies.switcher.pinnedRoots).toEqual(["/memory/checkouts/demo/baseline"]);
    expect(dependencies.switcher.calls).toEqual([
      { projectRoot: "/memory/checkouts/demo/candidate", specs: SPECS },
    ]);
    const events = dependencies.logger.records.map((record) => record.event);
    expect(events).toContain("project_pinned_to_upstream");
    expect(events).toContain("project_switched");
  });

  it("checkDependents compares the generated files after normalizing the product name", async () => {
    const { run } = setUp();

    const [result] = await run();

    expect(result?.generatedFiles.map((file) => [file.path, file.status])).toEqual([
      ["gen/schema.ts", GeneratedFileStatus.Identical],
      ["gen/never.ts", GeneratedFileStatus.Missing],
    ]);
  });

  it("checkDependents stores the results and erases the checkouts of a passed project", async () => {
    const { dependencies, run } = setUp();

    const results = await run();

    const stored = dependencies.cache.files.get(DEPENDENTS_RESULTS_PATH) ?? "";
    expect(decodeDependentResults(stored)).toEqual(results);
    expect(dependencies.work.files.has("checkouts/demo/baseline/app/gen/schema.ts")).toBe(false);
  });

  it("checkDependents marks a step that fails only after the switch as a regression", async () => {
    const { dependencies, run } = setUp(
      failingInCandidate("pnpm run typecheck", { exitCode: 2, outputTail: "error TS2322" }),
    );

    const [result] = await run();

    expect(result).toMatchObject({ status: DependentStatus.Regressed, failedStep: "typecheck" });
    expect(result?.candidate.slice(-2)).toEqual([
      {
        name: "typecheck",
        status: StepStatus.Failed,
        durationMs: 7,
        outputExcerpt: "error TS2322",
      },
      { name: "test", status: StepStatus.NotRun, durationMs: 0, outputExcerpt: "" },
    ]);
    expect(dependencies.work.files.has("checkouts/demo/candidate/app/gen/schema.ts")).toBe(true);
  });

  it("checkDependents reports a step that runs out of time as timed out", async () => {
    const { run } = setUp(failingInCandidate("pnpm test", { exitCode: null, isTimedOut: true }));

    const [result] = await run();

    expect(result?.candidate.at(-1)?.status).toBe(StepStatus.TimedOut);
  });

  it("checkDependents without the commit reports a baseline failure and runs nothing else", async () => {
    const { dependencies, run } = setUp((r) =>
      commandOf(r).startsWith("git fetch") ? { exitCode: 128 } : defaultEffect(r),
    );

    const [result] = await run();

    expect(result).toMatchObject({ status: DependentStatus.BaselineFailed, failedStep: "fetch" });
    expect(result?.candidate).toEqual([]);
    expect(dependencies.runner.commandLines.some((line) => line.includes("worktree"))).toBe(false);
  });

  it("checkDependents does not fetch a commit the repository already has", async () => {
    const { dependencies, run } = setUp((r) =>
      commandOf(r).startsWith("git cat-file") ? {} : defaultEffect(r),
    );

    const [result] = await run();

    expect(result?.baseline[0]?.name).toBe("checkout");
    expect(dependencies.runner.commandLines.some((line) => line.startsWith("git fetch"))).toBe(
      false,
    );
  });

  it("checkDependents skips the steps of a checkout that failed", async () => {
    const { run } = setUp((r) =>
      commandOf(r).startsWith("git worktree add") ? { exitCode: 128 } : defaultEffect(r),
    );

    const [result] = await run();

    expect(result).toMatchObject({
      status: DependentStatus.BaselineFailed,
      failedStep: "checkout",
    });
    expect(result?.baseline.slice(2).every((step) => step.status === StepStatus.NotRun)).toBe(true);
  });

  it("checkDependents logs a failed worktree prune and goes on", async () => {
    const { dependencies, run } = setUp((r) =>
      commandOf(r) === "git worktree prune"
        ? { exitCode: 1, outputTail: "locked" }
        : defaultEffect(r),
    );

    const [result] = await run();

    expect(result?.status).toBe(DependentStatus.Passed);
    expect(dependencies.logger.records).toContainEqual({
      level: "warn",
      event: "worktree_prune_failed",
      fields: { project: "demo", output: "locked" },
    });
  });

  it("checkDependents warns when a rewrite changes nothing", async () => {
    const { dependencies, input } = setUp();
    const switcher = new FakeProjectSwitcher({ changedFileCount: 0, replacementCount: 0 });

    await checkDependents({ ...dependencies, switcher }, input);

    expect(
      dependencies.logger.records.map((record) => [record.level, record.event]),
    ).toContainEqual(["warn", "project_rewrite_changed_nothing"]);
  });
});
