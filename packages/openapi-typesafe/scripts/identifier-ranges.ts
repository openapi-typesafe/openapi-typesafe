import { writeFile } from "node:fs/promises";
import ts from "typescript";

/**
 * Write src/domain/ir/newer-identifier-ranges.ts: the code points that the running Node.js counts
 * as `ID_Start` / `ID_Continue` and TypeScript's scanner does not (Unicode newer than its tables).
 * Run it after a Node.js or TypeScript update when test/domain/ir/identifier-text.test.ts fails.
 */

const OUTPUT = new URL("../src/domain/ir/newer-identifier-ranges.ts", import.meta.url);
const FIRST_NON_ASCII = 0x80;
const MAX_CODE_POINT = 0x10ffff;
const SURROGATES = { first: 0xd800, last: 0xdfff };
const HEX = 16;

type Range = readonly [number, number];

function newerRanges(isRuntime: (text: string) => boolean, isTypeScript: (point: number) => boolean) {
  const ranges: Range[] = [];
  let start: number | undefined;
  for (let point = FIRST_NON_ASCII; point <= MAX_CODE_POINT + 1; point++) {
    const isSurrogate = point >= SURROGATES.first && point <= SURROGATES.last;
    const isNewer =
      point <= MAX_CODE_POINT && !isSurrogate && isRuntime(String.fromCodePoint(point)) && !isTypeScript(point);
    if (isNewer && start === undefined) {
      start = point;
    } else if (!isNewer && start !== undefined) {
      ranges.push([start, point - 1]);
      start = undefined;
    }
  }
  return ranges;
}

/** One regex class item per line: `"\\u{88F}"` or `"\\u{1C89}-\\u{1C8A}"` (escapes for RegExp). */
function classItems(ranges: readonly Range[]): string {
  const escapePoint = (point: number) => `\\\\u{${point.toString(HEX).toUpperCase()}}`;
  return ranges
    .map(([first, last]) => (first === last ? escapePoint(first) : `${escapePoint(first)}-${escapePoint(last)}`))
    .map((item) => `  "${item}",`)
    .join("\n");
}

const start = newerRanges(
  (text) => /^\p{ID_Start}$/u.test(text),
  (point) => ts.isIdentifierStart(point, ts.ScriptTarget.ESNext),
);
const part = newerRanges(
  (text) => /^\p{ID_Continue}$/u.test(text),
  (point) => ts.isIdentifierPart(point, ts.ScriptTarget.ESNext),
);

const source = `// Generated by scripts/identifier-ranges.ts (Node.js ${process.versions.node}, Unicode
// ${process.versions.unicode}, TypeScript ${ts.version}). Do not edit.

/** \`ID_Start\` code points that TypeScript's scanner does not accept, as regex class items. */
export const NEWER_IDENTIFIER_START: readonly string[] = [
${classItems(start)}
];

/** \`ID_Continue\` code points that TypeScript's scanner does not accept, as regex class items. */
export const NEWER_IDENTIFIER_PART: readonly string[] = [
${classItems(part)}
];
`;

await writeFile(OUTPUT, source);
process.stdout.write(`start ranges: ${start.length}, part ranges: ${part.length}\n`);
