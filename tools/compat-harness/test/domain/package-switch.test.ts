import { describe, expect, it } from "vitest";
import {
  pinSwitchedDependencies,
  pinUpstreamVersions,
  type SwitchedPackageSpecs,
  switchModuleSpecifiers,
  switchPackageManifest,
} from "../../src/domain/package-switch.ts";

const SPECS: SwitchedPackageSpecs = {
  "openapi-typesafe": "file:/p/openapi-typesafe.tgz",
  "openapi-typesafe-fetch": "file:/p/fetch.tgz",
  "openapi-typesafe-react-query": "file:/p/react-query.tgz",
  "openapi-typesafe-helpers": "file:/p/helpers.tgz",
};

const manifest = (value: unknown, indent: string | number = 2): string =>
  `${JSON.stringify(value, null, indent)}\n`;

describe("switchPackageManifest", () => {
  it("switchPackageManifest replaces the original dependencies in place with the switched specs", () => {
    const text = manifest({
      dependencies: { a: "1", "openapi-fetch": "^0.17.0", z: "2" },
      devDependencies: { "openapi-typescript": "^7.13.0" },
      optionalDependencies: { "openapi-react-query": "0.5.4" },
    });

    const switched = switchPackageManifest(text, SPECS);

    expect(JSON.parse(switched.text)).toEqual({
      dependencies: { a: "1", "openapi-typesafe-fetch": "file:/p/fetch.tgz", z: "2" },
      devDependencies: { "openapi-typesafe": "file:/p/openapi-typesafe.tgz" },
      optionalDependencies: { "openapi-typesafe-react-query": "file:/p/react-query.tgz" },
    });
    expect(Object.keys(JSON.parse(switched.text).dependencies)).toEqual([
      "a",
      "openapi-typesafe-fetch",
      "z",
    ]);
    expect(switched.replacementCount).toBe(3);
  });

  it("switchPackageManifest lets switched peer dependencies accept any version", () => {
    const text = manifest({ peerDependencies: { "openapi-fetch": "0.17", swr: "2" } });

    const switched = switchPackageManifest(text, SPECS);

    expect(JSON.parse(switched.text).peerDependencies).toEqual({
      "openapi-typesafe-fetch": "*",
      swr: "2",
    });
  });

  it("switchPackageManifest renames the generator command but not helpers or paths", () => {
    const text = manifest({
      scripts: {
        gen: "npx openapi-typescript ./a.json -o b.ts && openapi-typescript c.yaml",
        keep: "node node_modules/openapi-typescript/bin/cli.js && echo openapi-typescript-helpers",
        count: 3,
      },
    });

    const switched = switchPackageManifest(text, SPECS);

    expect(JSON.parse(switched.text).scripts).toEqual({
      gen: "npx openapi-typesafe ./a.json -o b.ts && openapi-typesafe c.yaml",
      keep: "node node_modules/openapi-typescript/bin/cli.js && echo openapi-typescript-helpers",
      count: 3,
    });
    expect(switched.replacementCount).toBe(2);
  });

  it("switchPackageManifest keeps tab indentation and a missing final newline", () => {
    const text = JSON.stringify({ dependencies: { "openapi-fetch": "1" } }, null, "\t");

    const switched = switchPackageManifest(text, SPECS);

    expect(switched.text).toBe(
      JSON.stringify(
        { dependencies: { "openapi-typesafe-fetch": "file:/p/fetch.tgz" } },
        null,
        "\t",
      ),
    );
  });

  it("switchPackageManifest returns a manifest without original packages unchanged", () => {
    const text = '{ "name": "x", "dependencies": { "react": "18" } }';

    expect(switchPackageManifest(text, SPECS)).toEqual({ text, replacementCount: 0 });
  });

  it("switchPackageManifest returns a non-object manifest unchanged", () => {
    expect(switchPackageManifest("[1]", SPECS)).toEqual({ text: "[1]", replacementCount: 0 });
  });
});

describe("switchModuleSpecifiers", () => {
  it("switchModuleSpecifiers rewrites quoted specifiers with and without subpaths", () => {
    const text = [
      'import createClient from "openapi-fetch";',
      "import type { paths } from 'openapi-typescript-helpers';",
      'import x from "openapi-react-query/dist/index.js";',
      'const api = await import("openapi-typescript");',
    ].join("\n");

    const switched = switchModuleSpecifiers(text);

    expect(switched.text).toBe(
      [
        'import createClient from "openapi-typesafe-fetch";',
        "import type { paths } from 'openapi-typesafe-helpers';",
        'import x from "openapi-typesafe-react-query/dist/index.js";',
        'const api = await import("openapi-typesafe");',
      ].join("\n"),
    );
    expect(switched.replacementCount).toBe(4);
  });

  it("switchModuleSpecifiers leaves other strings and unquoted names alone", () => {
    const text = [
      "// generated by openapi-typescript",
      'import a from "openapi-fetch-gen";',
      'import b from "@scope/openapi-fetch";',
      "const mixed = \"openapi-fetch';",
    ].join("\n");

    expect(switchModuleSpecifiers(text)).toEqual({ text, replacementCount: 0 });
  });
});

describe("pinSwitchedDependencies", () => {
  it("pinSwitchedDependencies points sibling dependencies at the given specs", () => {
    const text = manifest({
      name: "openapi-typesafe-fetch",
      dependencies: { "openapi-typesafe-helpers": "^0.0.0", other: "1" },
      peerDependencies: { "openapi-typesafe-fetch": "^0.0.0" },
    });

    const pinned = pinSwitchedDependencies(text, SPECS);

    expect(JSON.parse(pinned.text)).toEqual({
      name: "openapi-typesafe-fetch",
      dependencies: { "openapi-typesafe-helpers": "file:/p/helpers.tgz", other: "1" },
      peerDependencies: { "openapi-typesafe-fetch": "^0.0.0" },
    });
    expect(pinned.replacementCount).toBe(1);
  });

  it("pinSwitchedDependencies returns a manifest without dependencies unchanged", () => {
    const text = manifest({ name: "openapi-typesafe-helpers" });

    expect(pinSwitchedDependencies(text, SPECS)).toEqual({ text, replacementCount: 0 });
    expect(pinSwitchedDependencies("null", SPECS)).toEqual({ text: "null", replacementCount: 0 });
  });
});

describe("pinUpstreamVersions", () => {
  it("pinUpstreamVersions pins installed original packages to the fork-base releases", () => {
    const text = manifest({
      dependencies: { "openapi-fetch": "^0.13.1", react: "18" },
      devDependencies: { "openapi-typescript": "catalog:", "openapi-typescript-helpers": "0.0.15" },
      optionalDependencies: { "openapi-react-query": "~0.2.0" },
      peerDependencies: { "openapi-fetch": "0.13" },
      scripts: { gen: "openapi-typescript a.json" },
    });

    const pinned = pinUpstreamVersions(text);

    expect(JSON.parse(pinned.text)).toEqual({
      dependencies: { "openapi-fetch": "0.17.0", react: "18" },
      devDependencies: { "openapi-typescript": "7.13.0", "openapi-typescript-helpers": "0.1.0" },
      optionalDependencies: { "openapi-react-query": "0.5.4" },
      peerDependencies: { "openapi-fetch": "0.13" },
      scripts: { gen: "openapi-typescript a.json" },
    });
    expect(pinned.replacementCount).toBe(4);
  });
});
