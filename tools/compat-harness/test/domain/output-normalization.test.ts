import { describe, expect, it } from "vitest";
import {
  normalizeGeneratedOutput,
  PRODUCT_NAME_PLACEHOLDER,
} from "../../src/domain/output-normalization.ts";

describe("normalizeGeneratedOutput", () => {
  it("normalizeGeneratedOutput converts CRLF and CR to LF and strips trailing whitespace", () => {
    expect(normalizeGeneratedOutput("a  \r\nb\t\rc")).toBe("a\nb\nc");
  });

  it.each(["openapi-typescript", "openapi-typesafe"])(
    "normalizeGeneratedOutput replaces %s in the header",
    (name) => {
      const header = ` * This file was auto-generated by ${name}.`;

      expect(normalizeGeneratedOutput(header)).toBe(
        ` * This file was auto-generated by ${PRODUCT_NAME_PLACEHOLDER}.`,
      );
    },
  );

  it("normalizeGeneratedOutput replaces the product name in both discriminator JSDoc forms", () => {
    const text =
      "enum property replaced by openapi-typescript\ndiscriminator enum property added by openapi-typesafe";

    expect(normalizeGeneratedOutput(text)).toBe(
      `enum property replaced by ${PRODUCT_NAME_PLACEHOLDER}\ndiscriminator enum property added by ${PRODUCT_NAME_PLACEHOLDER}`,
    );
  });

  it("normalizeGeneratedOutput leaves other mentions of the product untouched", () => {
    const description = "/** @description Generated with openapi-typescript */";

    expect(normalizeGeneratedOutput(description)).toBe(description);
  });
});
