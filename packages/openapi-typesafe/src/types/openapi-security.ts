import type { Extensable } from "./openapi-common.js";
import type { ComponentsObject } from "./openapi-document.js";

/**
 * [4.8.27] Security Scheme Object
 * Defines a security scheme that can be used by the operations.
 */
export type SecuritySchemeObject = {
  /**
   * A description for security scheme. CommonMark syntax MAY be used for rich text representation.
   */
  description?: string;
  [key: `x-${string}`]: any;
} & (
  | {
      /** REQUIRED. The type of the security scheme. */
      type: "apiKey";
      /** REQUIRED. The name of the header, query or cookie parameter to be used. */
      name: string;
      /** REQUIRED. The location of the API key. */
      in: "query" | "header" | "cookie";
    }
  | {
      /** REQUIRED. The type of the security scheme. */
      type: "http";
      /**
       * REQUIRED. The name of the HTTP Authorization scheme to be used in the Authorization header
       * as defined in [RFC7235]. The values used SHOULD be registered in the IANA Authentication
       * Scheme registry.
       */
      scheme: string;
      /**
       * A hint to the client to identify how the bearer token is formatted. Bearer tokens are
       * usually generated by an authorization server, so this information is primarily for
       * documentation purposes.
       */
      bearer?: string;
    }
  | {
      /** REQUIRED. The type of the security scheme. */
      type: "mutualTLS";
    }
  | {
      /** REQUIRED. Tye type of the security scheme. */
      type: "oauth2";
      /** REQUIRED. An object containing configuration information for the flow types supported. */
      flows: OAuthFlowsObject;
    }
  | {
      /** REQUIRED. Tye type of the security scheme. */
      type: "openIdConnect";
      /**
       * REQUIRED. OpenId Connect URL to discover OAuth2 configuration values. This MUST be in the
       * form of a URL. The OpenID Connect standard requires the use of TLS.
       */
      openIdConnectUrl: string;
    }
);

/**
 * [4.8.26] OAuth Flows Object
 * Allows configuration of the supported OAuth Flows.
 */
export interface OAuthFlowsObject extends Extensable {
  /** Configuration for the OAuth Implicit flow */
  implicit?: OAuthFlowObject;
  /** Configuration for the OAuth Resource Owner Password flow */
  password?: OAuthFlowObject;
  /**
   * Configuration for the OAuth Client Credentials flow. Previously called `application` in OpenAPI
   * 2.0.
   */
  clientCredentials?: OAuthFlowObject;
  /**
   * Configuration for the OAuth Authorization Code flow. Previously called `accessCode` in OpenAPI
   * 2.0.
   */
  authorizationCode?: OAuthFlowObject;
}

/**
 * [4.8.29] OAuth Flow Object
 * Configuration details for a supported OAuth Flow
 */
export interface OAuthFlowObject extends Extensable {
  /**
   * REQUIRED. The authorization URL to be used for this flow. This MUST be in the form of a URL.
   * The OAuth2 standard requires the use of TLS.
   */
  authorizationUrl: string;
  /**
   * REQUIRED. The token URL to be used for this flow. This MUST be in the form of a URL. The OAuth2
   * standard requires the use of TLS.
   */
  tokenUrl: string;
  /**
   * The URL to be used for obtaining refresh tokens. This MUST be in the form of a URL. The OAuth2
   * standard requires the use of TLS.
   */
  refreshUrl: string;
  /**
   * REQUIRED. The available scopes for the OAuth2 security scheme. A map between the scope name and
   * a short description for it. The map MAY be empty.
   */
  scopes: { [name: string]: string };
}

/**
 * [4.8.30] Security Requirements Object
 * Lists the required security schemes to execute this operation. The name used for each property
 * MUST correspond to a security scheme declared in the Security Schemes under the Components
 * Object.
 */
export type SecurityRequirementObject = {
  [P in keyof ComponentsObject["securitySchemes"]]?: string[];
};
