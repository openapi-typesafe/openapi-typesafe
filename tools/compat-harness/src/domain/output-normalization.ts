/**
 * Placeholder that replaces the generator's product name in output. The fork renamed the product
 * (task 1.1), which is an intended difference that must not count as drift.
 */
export const PRODUCT_NAME_PLACEHOLDER = "<generator>";

/**
 * Places where generated text names the product (the original or the fork): the file header and the
 * discriminator JSDoc. Group 1 is the text before the name.
 */
const PRODUCT_NAME_CONTEXTS = [
  /(This file was auto-generated by )openapi-(?:typescript|typesafe)/g,
  new RegExp(
    "((?:enum property replaced|discriminator enum property added) by )" +
      "openapi-(?:typescript|typesafe)",
    "g",
  ),
];

const TRAILING_WHITESPACE = /[ \t]+$/gm;
const WINDOWS_LINE_ENDINGS = /\r\n?/g;

/**
 * Normalize generated output for a text comparison: LF line endings, no trailing whitespace, and
 * the product name replaced in the two places the generator writes it. Other occurrences (for
 * example a schema that mentions "openapi-typescript" in a description) are left untouched on
 * purpose.
 */
export function normalizeGeneratedOutput(text: string): string {
  let normalized = text.replace(WINDOWS_LINE_ENDINGS, "\n").replace(TRAILING_WHITESPACE, "");
  for (const context of PRODUCT_NAME_CONTEXTS) {
    normalized = normalized.replace(context, `$1${PRODUCT_NAME_PLACEHOLDER}`);
  }
  return normalized;
}
