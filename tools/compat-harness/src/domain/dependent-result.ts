import type { TextComparison } from "./text-comparison.ts";

/** The two runs of a project: as it is, and switched to openapi-typesafe. */
export const RunVariant = {
  Baseline: "baseline",
  Candidate: "candidate",
} as const;

export type RunVariant = (typeof RunVariant)[keyof typeof RunVariant];

/** Outcome of one step of a dependent project run. */
export const StepStatus = {
  Passed: "passed",
  Failed: "failed",
  TimedOut: "timed-out",
  /** An earlier step failed; every step depends on the ones before it. */
  NotRun: "not-run",
} as const;

export type StepStatus = (typeof StepStatus)[keyof typeof StepStatus];

export interface StepResult {
  readonly name: string;
  readonly status: StepStatus;
  readonly durationMs: number;
  /** The end of the step output, where tools print their errors; empty for a passed step. */
  readonly outputExcerpt: string;
}

/** Verdict of one dependent project. */
export const DependentStatus = {
  /** Every step that passed as is also passes after the switch. */
  Passed: "passed",
  /** A step passed as is and fails after the switch: a compatibility problem. */
  Regressed: "regressed",
  /** The project fails as is, so the switch cannot be judged; the manifest entry needs work. */
  BaselineFailed: "baseline-failed",
} as const;

export type DependentStatus = (typeof DependentStatus)[keyof typeof DependentStatus];

/** How a file generated by the original compares to the same file generated by the candidate. */
export const GeneratedFileStatus = {
  Identical: "identical",
  Different: "different",
  /** A run did not produce the file, so there is nothing to compare. */
  Missing: "missing",
} as const;

export type GeneratedFileStatus = (typeof GeneratedFileStatus)[keyof typeof GeneratedFileStatus];

export interface GeneratedFileComparison {
  readonly path: string;
  readonly status: GeneratedFileStatus;
  readonly firstDifferentLine: number | null;
  readonly differentLineCount: number;
  readonly intentionalDifferenceIds: readonly string[];
}

export interface DependentResult {
  readonly projectId: string;
  readonly repository: string;
  readonly commit: string;
  readonly status: DependentStatus;
  /** First step that did not pass in the run that decided the status; null when passed. */
  readonly failedStep: string | null;
  readonly baseline: readonly StepResult[];
  readonly candidate: readonly StepResult[];
  readonly generatedFiles: readonly GeneratedFileComparison[];
}

const firstUnpassedStep = (steps: readonly StepResult[]): StepResult | undefined =>
  steps.find((step) => step.status !== StepStatus.Passed);

/** Decide the status of a project from its baseline and candidate step results. */
export function classifyDependent(
  baseline: readonly StepResult[],
  candidate: readonly StepResult[],
): { readonly status: DependentStatus; readonly failedStep: string | null } {
  const baselineFailure = firstUnpassedStep(baseline);
  if (baselineFailure !== undefined) {
    return { status: DependentStatus.BaselineFailed, failedStep: baselineFailure.name };
  }
  const candidateFailure = firstUnpassedStep(candidate);
  if (candidateFailure !== undefined) {
    return { status: DependentStatus.Regressed, failedStep: candidateFailure.name };
  }
  return { status: DependentStatus.Passed, failedStep: null };
}

/** Comparison entry for a generated file that one of the runs did not produce. */
export function missingGeneratedFile(path: string): GeneratedFileComparison {
  return {
    path,
    status: GeneratedFileStatus.Missing,
    firstDifferentLine: null,
    differentLineCount: 0,
    intentionalDifferenceIds: [],
  };
}

/** Comparison entry for a generated file both runs produced. */
export function comparedGeneratedFile(
  path: string,
  comparison: TextComparison,
): GeneratedFileComparison {
  return {
    path,
    status: comparison.isIdentical ? GeneratedFileStatus.Identical : GeneratedFileStatus.Different,
    firstDifferentLine: comparison.firstDifferentLine,
    differentLineCount: comparison.differentLineCount,
    intentionalDifferenceIds: comparison.intentionalDifferenceIds,
  };
}

/** Totals of a dependents run for the report. */
export interface DependentsSummary {
  readonly total: number;
  readonly passed: number;
  readonly regressed: number;
  readonly baselineFailed: number;
  readonly generatedFiles: number;
  readonly identicalGeneratedFiles: number;
}

export function summarizeDependents(results: readonly DependentResult[]): DependentsSummary {
  const count = (status: DependentStatus): number =>
    results.filter((result) => result.status === status).length;
  const files = results.flatMap((result) => result.generatedFiles);
  return {
    total: results.length,
    passed: count(DependentStatus.Passed),
    regressed: count(DependentStatus.Regressed),
    baselineFailed: count(DependentStatus.BaselineFailed),
    generatedFiles: files.length,
    identicalGeneratedFiles: files.filter((file) => file.status === GeneratedFileStatus.Identical)
      .length,
  };
}
