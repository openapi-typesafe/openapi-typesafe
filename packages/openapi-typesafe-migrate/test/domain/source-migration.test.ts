import { describe, expect, it } from "vitest";
import { migrateModuleSpecifiers } from "../../src/domain/source-migration.js";

describe("migrateModuleSpecifiers", () => {
  it("migrateModuleSpecifiers renames quoted package names in any quote style", () => {
    const text = [
      'import createClient from "openapi-fetch";',
      "import type { paths } from 'openapi-typescript-helpers';",
      "const api = await import(`openapi-typescript`);",
      'vi.mock("openapi-react-query");',
    ].join("\n");

    const migrated = migrateModuleSpecifiers(text);

    expect(migrated.text).toBe(
      [
        'import createClient from "openapi-typesafe-fetch";',
        "import type { paths } from 'openapi-typesafe-helpers';",
        "const api = await import(`openapi-typesafe`);",
        'vi.mock("openapi-typesafe-react-query");',
      ].join("\n"),
    );
    expect(
      migrated.changes.map((change) => change.kind === "specifier-renamed" && change.line),
    ).toEqual([1, 2, 3, 4]);
    expect(migrated.manualSteps).toEqual([]);
  });

  it("migrateModuleSpecifiers reports deep imports", () => {
    const migrated = migrateModuleSpecifiers('import x from "openapi-fetch/dist/index.js";');

    expect(migrated.text).toBe('import x from "openapi-typesafe-fetch/dist/index.js";');
    expect(migrated.manualSteps).toEqual([
      { kind: "deep-import", line: 1, specifier: "openapi-typesafe-fetch/dist/index.js" },
    ]);
  });

  it("migrateModuleSpecifiers leaves comments, scoped and longer names alone", () => {
    const text = [
      "// generated by openapi-typescript",
      'import a from "openapi-fetch-gen";',
      'import b from "@scope/openapi-fetch";',
      "const mixed = \"openapi-fetch';",
    ].join("\n");

    expect(migrateModuleSpecifiers(text)).toEqual({ text, changes: [], manualSteps: [] });
  });
});
